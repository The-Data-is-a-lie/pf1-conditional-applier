"""Produce the SELF-CONTAINED macro: apply-conditionals.bundled.js.

Inlines the /data bundle into the macro (replacing `const EMBEDDED_DATA = null;`) so the macro needs
NO network — paste it into a Foundry Script macro and run. Regenerate after build_data.py:

    C:\\Python310\\python.exe build/bundle_macro.py

Data is embedded as ASCII-escaped JSON (\\uXXXX), which is always valid inside a JS source file, so
there are no UTF-8 / line-separator pitfalls.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
DATA = ROOT / "data"
SRC = ROOT / "src" / "apply-conditionals.macro.js"
OUT = ROOT / "apply-conditionals.bundled.js"
FILES = ["spell_riders", "spell_changes", "maneuver_changes", "combat_talent_conditionals",
         "magic_talent_conditionals", "spell_damage_index", "feat_conditionals",
         "weapon_quality_conditionals", "class_feature_conditionals"]
MARKER = "const EMBEDDED_DATA = null;"


def main():
    bundle = {f: json.loads((DATA / f).with_suffix(".json").read_text(encoding="utf-8")) for f in FILES}
    # ensure_ascii=True -> pure-ASCII \uXXXX, safe as a JS literal; compact separators keep it small.
    blob = json.dumps(bundle, ensure_ascii=True, separators=(",", ":"))
    src = SRC.read_text(encoding="utf-8")
    if MARKER not in src:
        raise SystemExit(f"marker not found in {SRC.name!r}: {MARKER!r}")
    banner = ("// ===== SELF-CONTAINED BUILD (generated by build/bundle_macro.py) =====\n"
              "// Data is embedded below; this macro needs NO network. Paste into a Foundry Script\n"
              "// macro and run. To refresh, edit the source macro / data and re-run the bundler.\n")
    out = banner + src.replace(MARKER, f"const EMBEDDED_DATA = {blob};")
    OUT.write_text(out, encoding="utf-8")
    counts = {f: len(bundle[f]) for f in FILES}
    print(f"wrote {OUT.name}  ({OUT.stat().st_size:,} bytes)")
    print("  embedded entry counts:")
    for f, n in counts.items():
        print(f"    {f:<32} {n:>5}")


if __name__ == "__main__":
    main()
